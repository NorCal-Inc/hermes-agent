def _persisted_session_id(session_id: Optional[str]) -> Optional[str]:
    """Return a session id only when it is present in this profile's state.db."""
    if not session_id:
        return None
    try:
        from hermes_state import SessionDB
        from hermes_constants import get_hermes_home

        state = SessionDB(db_path=get_hermes_home() / "state.db", read_only=True)
    except Exception:  # state.db may not exist for a CLI/dashboard invocation
        logger.debug("Could not open state.db to verify Kanban provenance", exc_info=True)
        return None
    try:
        return session_id if state.get_session(session_id) else None
    finally:
        state.close()


@_kanban_handler("kanban_create")
def _handle_create(args: dict, **kw) -> str:
    """Create a (child) task; orchestrator workers use this to fan out."""
    _reject_delegated_child_mutation("kanban_create")
    # Rule 6 (production authority): no agent-facing path may grant
    # production authority to a card. The structured field is set only by an
    # interactive operator through ``hermes kanban create
    # --production-action``; this tool refuses the argument in every form,
    # even an empty list, so the refusal is unambiguous in the transcript.
    _check(not any(k in args for k in ("production_actions", "production_action")),
           "production_actions cannot be set through kanban_create: a worker or agent "
           "never grants production authority to a card. Only an interactive operator "
           "may set it, at creation, with `hermes kanban create --production-action <role>`.")
    title = _require_text(args, "title")
    assignee = args.get("assignee")
    _check(assignee, "assignee is required — name the profile that should execute this "
                     "task (the dispatcher will only spawn tasks with an assignee)")
    # Workspace sharing is always explicit: omitted fields mean a fresh scratch workspace
    # even for a dispatcher-spawned creator (reusing the parent's path would let a child
    # mutate review evidence or race its checkout). Project identity is the one safe thing
    # to inherit implicitly (the DB turns it into a fresh per-task worktree).
    workspace_kind, workspace_path = args.get("workspace_kind"), args.get("workspace_path")
    # See #67567. ``project=""`` is an explicit "no project" (no ``or`` collapse, #106342).
    project_id = args["project"] if "project" in args else args.get("project_id")
    project_source_task_id = None
    triage, skills, goal_mode = (
        _parse_bool_arg(args, "triage"), _coerce_str_list(args.get("skills"), "skills", "skill names"),
        _parse_bool_arg(args, "goal_mode"))
    model_override, provider_override = args.get("model"), args.get("provider")
    _check(model_override or not provider_override, "'provider' requires 'model' to be set as well")
    parents = _coerce_str_list(args.get("parents") or [], "parents", "task ids")
    # NorCal lanes + structured repair linkage: any one of recovery_owner /
    # repairs_task_id / umbrella_task_id arms create_task's declares_repair
    # guard, which requires all three and establishes the relations atomically
    # in the same transaction as the insert — a card cannot land here linked
    # to only a subject or only an owner. Omitted entirely, this call behaves
    # exactly as before (an ordinary card, or a repair declared only in prose).
    executor_lane = args.get("executor_lane")
    recovery_gate_cmd = args.get("recovery_gate_cmd")
    recovery_owner = args.get("recovery_owner")
    repairs_task_id = args.get("repairs_task_id")
    umbrella_task_id = args.get("umbrella_task_id")
    control_plane_authority = str(args.get("control_plane_authority") or "").strip() or None
    with _board(args.get("board")) as (kb, conn):
        from gateway.session_context import get_session_env
        from tools.async_delegation import _current_origin_session_id
        self_tid = (os.environ.get("HERMES_KANBAN_TASK")
                    if _is_dispatcher_owned_worker() else None)
        self_task = kb.get_task(conn, self_tid) if self_tid else None
        # The worker/API runtime may be transient; the owning task's origin is durable.
        # The ambient id is the request-scoped ContextVar binding, not the process-global
        # os.environ: in a multi-session gateway the env holds the LAST agent built, and an
        # id that never reached its ``sessions`` row is provenance pointing at nothing.
        session_id = (_persisted_session_id(args.get("session_id"))
                      or (self_task.session_id if self_task else None)
                      or _persisted_session_id(_current_origin_session_id())
                      or _persisted_session_id(get_session_env("HERMES_SESSION_ID", "")))
        if project_id is None and workspace_kind is None and workspace_path is None:
            if self_task is not None and self_task.project_id:
                project_id, project_source_task_id = self_task.project_id, self_task.id
        if control_plane_authority:
            # Naming authority is itself an operator decision: admitted only
            # from recorded facts (_operator_authority), never from the
            # worker's assertion. Without this gate any worker could reopen
            # control-plane work by typing 'operator:me'.
            basis, refusal, _adm = _operator_authority(kb, conn, _default_actor(args))
            _check(basis is not None, f"control_plane_authority refused: this session {refusal}")
        new_tid = kb.create_task(
            conn, title=str(title).strip(), body=args.get("body"), assignee=str(assignee),
            parents=tuple(parents), tenant=args.get("tenant") or os.environ.get("HERMES_TENANT"),
            priority=_opt_int(args.get("priority"), 0),
            workspace_kind=workspace_kind, workspace_path=workspace_path, project_id=project_id,
            # Board-project inheritance must read the board this call opened, not the
            # session's current board.
            board=args.get("board"),
            project_source_task_id=project_source_task_id, triage=triage,
            creator_task_id=self_tid,
            idempotency_key=args.get("idempotency_key"),
            max_runtime_seconds=_opt_int(args.get("max_runtime_seconds")), skills=skills,
            model_override=model_override, provider_override=provider_override,
            goal_mode=goal_mode, goal_max_turns=_opt_int(args.get("goal_max_turns")),
            completion_contract=args.get("completion_contract"),
            initial_status=str(args.get("initial_status") or "running"),
            created_by=_persisted_identity(), session_id=session_id,
            executor_lane=executor_lane, recovery_gate_cmd=recovery_gate_cmd,
            recovery_owner=recovery_owner, repairs_task_id=repairs_task_id,
            umbrella_task_id=umbrella_task_id,
            control_plane_authority=control_plane_authority)
        new_task = kb.get_task(conn, new_tid)
        # Postgres projection happens inside kb.create_task() itself (single
        # choke point covering CLI/recovery_lane/swarm callers too) — do not
        # double-post here.
        landed = _fields(new_task, _CREATED_FIELDS)
        wait = [e for e in kb.list_events(conn, new_tid) if e.kind == "dependency_wait"]
        gate = {"gated": True, "gated_by": wait[-1].payload["parent"]} if wait else {"gated": False}
        subscribed = _maybe_auto_subscribe(
            conn, new_tid, origin_session_id=session_id,
            direct_claude=bool(new_task and (
                new_task.executor_lane == getattr(kb, "EXECUTOR_LANE_CLAUDE", "claude")
                or (new_task.assignee or "").strip().lower() == "claude")),
            human_interactive=bool(new_task and (
                new_task.actor_kind or "").strip().lower() == "human_interactive"))
        return _ok(task_id=new_tid, **landed, **gate, subscribed=subscribed)


def _live_tui_session_key(session_key: str, profile: Optional[str]) -> str:
    """Re-resolve a TUI session key at subscribe time: the inherited ``HERMES_SESSION_KEY``
    can name a session already superseded by a compaction fork, and a subscription bound to
    the dead key silently drops every later completion notification (#110068). Maps the key
    to its continuation tip via the session store's lineage walk. Best-effort, fail-open:
    any error (or an unresolvable key) returns *session_key* unchanged."""
    db_path = None
    if profile and profile != "default":
        try:
            from pathlib import Path
            from hermes_cli.profiles import get_profile_dir, profile_exists
            if profile_exists(profile):
                db_path = Path(get_profile_dir(profile)) / "state.db"
        except Exception:
            db_path = None
    try:
        from hermes_state_registry import acquire, release_or_close
        db = acquire(db_path)
        try:
            return db.resolve_resume_session_id(session_key) or session_key
        finally:
            release_or_close(db)
    except Exception:
        return session_key


def _resolve_notify_target() -> Optional[dict[str, Any]]:
    """``kanban_db.add_notify_sub`` kwargs for the calling session, or None (CLI/cron/tests).
    Gateway sessions: ``HERMES_SESSION_PLATFORM``/``CHAT_ID`` ContextVars. TUI/desktop:
    those are cleared but the subprocess inherits ``HERMES_SESSION_KEY`` -> ``platform="tui"``
    for the TUI poller. ``HERMES_SESSION_ID`` is deliberately NOT a fallback: it is set for
    every CLI/ACP invocation and would auto-subscribe every CLI run."""
    from gateway.session_context import get_session_env as env
    platform, chat_id = env("HERMES_SESSION_PLATFORM", ""), env("HERMES_SESSION_CHAT_ID", "")
    if not platform or not chat_id:
        session_key = env("HERMES_SESSION_KEY", "") or os.environ.get("HERMES_SESSION_KEY", "")
        if not session_key:
            return None
        platform, chat_id = "tui", session_key
    chat_type = env("HERMES_SESSION_CHAT_TYPE", "") or None
    thread_id = env("HERMES_SESSION_THREAD_ID", "") or None
    message_id = env("HERMES_SESSION_MESSAGE_ID", "") or ""
    notifier_profile = env("HERMES_SESSION_PROFILE", "")
    if not notifier_profile:
        from hermes_cli.profiles import current_profile_name
        notifier_profile = current_profile_name("default")
    if platform == "tui":
        # The inherited key can be stale after a compaction fork (#110068): bind the
        # subscription to the live continuation tip, not the key the process started with.
        chat_id = _live_tui_session_key(chat_id, notifier_profile)
    delivery_metadata: dict[str, Any] = {
        k: v for k, v in (
            ("thread_id", thread_id), ("chat_type", chat_type),
            ("scope_id", env("HERMES_SESSION_SCOPE_ID", "")),
            ("parent_chat_id", env("HERMES_SESSION_PARENT_CHAT_ID", "")),
        ) if v}
    if (platform.lower() == "telegram" and thread_id
            and (chat_type or "").lower() in {"dm", "direct", "private"}):
        delivery_metadata["telegram_dm_topic_reply_fallback"] = True
        if str(thread_id) not in {"", "1"}:
            delivery_metadata["direct_messages_topic_id"] = str(thread_id)
        if message_id:
            delivery_metadata["telegram_reply_to_message_id"] = str(message_id)
    return dict(
        platform=platform, chat_id=chat_id, chat_type=chat_type, thread_id=thread_id,
        user_id=env("HERMES_SESSION_USER_ID", "") or None,
        user_id_alt=env("HERMES_SESSION_USER_ID_ALT", "") or None,
        notifier_profile=notifier_profile,
        delivery_mode="notify+wake" if platform != "tui" else None,
        delivery_metadata=delivery_metadata or None)


def _fallback_notify_target(
    cfg: Any, origin_session_id: Optional[str], direct_claude: bool, human_interactive: bool,
) -> Optional[dict[str, Any]]:
    """NorCal fallbacks when the session has no persistent channel.

    Direct-Claude cards created from Erika's stateless API path still carry
    the originating session id even though there is no push-capable
    platform/chat ContextVar: subscribe ``api_server`` on that id. A card
    admitted by an interactive human from the CLI has no socket to wake after
    the command exits: use the operator's configured kanban Telegram approval
    destination as a passive completion channel (``delivery_mode="notify"``).
    Cron/test/unattached tasks still no-op."""
    api_origin = (origin_session_id or "").strip()
    if not api_origin:
        return None
    if direct_claude:
        return dict(
            platform="api_server", chat_id=api_origin, chat_type=None, thread_id=None,
            user_id=None, user_id_alt=None, notifier_profile="default",
            delivery_mode="notify+wake", delivery_metadata=None)
    if not human_interactive:
        return None
    kcfg = cfg.get("kanban", {}) if isinstance(cfg, dict) else {}
    chat_id = str(kcfg.get("approval_telegram_chat_id") or "").strip()
    if not chat_id:
        return None
    chat_type = str(kcfg.get("approval_telegram_chat_type") or "") or None
    thread_id = str(kcfg.get("approval_telegram_thread_id") or "") or None
    delivery_metadata: dict[str, Any] = {
        k: v for k, v in (("thread_id", thread_id), ("chat_type", chat_type)) if v}
    if thread_id and (chat_type or "").lower() in {"dm", "direct", "private"}:
        delivery_metadata["telegram_dm_topic_reply_fallback"] = True
        if str(thread_id) not in {"", "1"}:
            delivery_metadata["direct_messages_topic_id"] = str(thread_id)
    return dict(
        platform="telegram", chat_id=chat_id, chat_type=chat_type, thread_id=thread_id,
        user_id=None, user_id_alt=None,
        notifier_profile=str(kcfg.get("approval_notifier_profile") or "default"),
        delivery_mode="notify", delivery_metadata=delivery_metadata or None)


def _maybe_auto_subscribe(
    conn: Any, task_id: str, *, origin_session_id: Optional[str] = None,
    direct_claude: bool = False, human_interactive: bool = False,
) -> bool:
    """Subscribe the calling session to completion/block events; True iff a row was
    written (surfaced as ``subscribed`` so an orchestrator can fall back to explicit
    ``kanban_notify-subscribe``). Gated by ``kanban.auto_subscribe_on_create`` (default
    True). Failures are logged and swallowed: bookkeeping must never fail kanban_create.
    ``origin_session_id`` / ``direct_claude`` / ``human_interactive`` feed the NorCal
    fallbacks in ``_fallback_notify_target`` when no session channel exists."""
    cfg: Any = {}
    try:
        cfg = load_config()
        if not cfg_get(cfg, "kanban", "auto_subscribe_on_create", default=True):
            return False
    except Exception:
        pass  # unreadable config keeps the user-friendly default (True)
    target = None
    try:
        target = _resolve_notify_target()
        if target is None:
            target = _fallback_notify_target(
                cfg, origin_session_id, direct_claude, human_interactive)
        if target is None:
            return False  # CLI / cron / test — no persistent channel
        if direct_claude and target["platform"] == "api_server":
            target["notifier_profile"] = "default"
        from hermes_cli import kanban_db_notify as _kbn
        # Inheritance and explicit subscriptions already encode the delivery policy.
        # Auto-subscribe must not turn a passive destination into an agent wake.
        if any(sub["platform"] == target["platform"] and sub["chat_id"] == target["chat_id"]
               and (sub["thread_id"] or "") == (target["thread_id"] or "")
               for sub in _kbn.list_notify_subs(conn, task_id)):
            return True
        _kbn.add_notify_sub(conn, task_id=task_id, **target)
        return True
    except Exception as _exc:
        logger.warning(
            "_maybe_auto_subscribe failed: %r (platform=%r key_set=%r)",
            _exc, target["platform"] if target else "", bool(target and target["chat_id"]))
        return False


